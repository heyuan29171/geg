const fs = require('fs');
const src = fs.readFileSync('js/data.js', 'utf8') + '\nglobalThis.__CARDS = CARDS; globalThis.__RARITY_LIST = RARITY_LIST; globalThis.__CARD_MAP = CARD_MAP; globalThis.__RARITIES = RARITIES; globalThis.__CONFIG = CONFIG;\n';
eval(src);
const CARDS = globalThis.__CARDS;
const RARITY_LIST = globalThis.__RARITY_LIST;
const CARD_MAP_NAME = Object.fromEntries(Object.entries(globalThis.__CARD_MAP).map(([k, v]) => [k, v.name]));
const RARITY_MAP = globalThis.__RARITIES;
const VERSION = globalThis.__CONFIG.VERSION;
const rname = id => RARITY_LIST.find(r => r.id === id).name;
const lines = [];
lines.push('# 卡片图占位说明');
lines.push('');
lines.push('把图片命名为 `img/cards/<卡片id>.jpg` 放入本目录，游戏会自动用它替换占位图。');
lines.push('');
lines.push('> 本表由 `js/data.js` 自动生成，对应游戏版本 **v' + VERSION + '**。改卡后请重新生成。');
lines.push('');
lines.push('## 卡片清单（共 ' + CARDS.length + ' 张）');
lines.push('');
lines.push('| NO. | id | 名字 | 稀有度 | 基础战力 | 重复→碎片 | 编队（含中心，共 N 张） | 描述 | 彩蛋文案 |');
lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
CARDS.forEach(c => {
  const fmt = c.formation.map(f => CARD_MAP_NAME[f]).join('、');
  const mem = (c.formation.length ? '『' + CARD_MAP_NAME[c.id] + '（中心）』+ ' + fmt : '独行（只有自己）');
  lines.push('| ' + String(c.no).padStart(3, '0') + ' | `' + c.id + '` | ' + c.name + ' | ' + rname(c.rarity) + (c.unique ? '（唯一）' : '') + ' | ' + RARITY_MAP[c.rarity].basePower + ' | ' + RARITY_MAP[c.rarity].frag + ' | ' + mem + ' | ' + c.desc + ' | 「' + c.flavor + '」 |');
});
lines.push('');
lines.push('建议尺寸：正方形 PNG（如 512×512），无圆角背景。');
fs.writeFileSync('img/cards/README.md', lines.join('\n') + '\n', 'utf8');
console.log('img/cards/README.md 已生成：' + CARDS.length + ' 张卡 @ v' + VERSION);